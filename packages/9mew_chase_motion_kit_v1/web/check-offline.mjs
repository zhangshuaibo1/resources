import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require((process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES||'')+'/playwright');
const web=path.dirname(fileURLToPath(import.meta.url));
const file=path.resolve(process.argv[2]||path.join(web,'../OPEN_ME.html'));
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const external=[],errors=[],checks=[];
const browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.PET_BROWSER_EXECUTABLE?{executablePath:process.env.PET_BROWSER_EXECUTABLE}:{})});
try{
  const context=await browser.newContext({viewport:{width:1440,height:1000},offline:true});
  const page=await context.newPage();
  page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(file).href);
  await page.waitForFunction(()=>window.mewChase?.inspect().loaded);
  await page.evaluate(()=>window.mewChase.pause());
  await page.evaluate(()=>window.mewChase.seek(10000));
  const state=await page.evaluate(()=>window.mewChase.inspect());
  assert.equal(state.cat.action,'chase-float');assert.equal(state.loadFailed,false);
  checks.push('All eight real atlases decode with network offline');
  await page.evaluate(()=>document.fonts.ready);
  assert(await page.evaluate(()=>document.fonts.check('16px "9mew Sans"')));
  checks.push('Bundled Chinese font loads from data URL');
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(100);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.getByRole('button',{name:'重新出发',exact:false}).click();await page.waitForTimeout(120);
  assert.equal(await page.evaluate(()=>window.mewChase.inspect().playing),true);
  checks.push('Mobile layout and replay work offline');
  assert.equal(await page.locator('#readme-link').getAttribute('href'),'https://github.com/zhangshuaibo1/resources/blob/9mew-chase-motion-v1.0.0/packages/9mew_chase_motion_kit_v1/README.md');
  checks.push('Standalone documentation link targets the immutable GitHub version');
  assert.deepEqual(external,[]);assert.deepEqual(errors,[]);
  checks.push('No external requests or JavaScript errors');
  const result={status:'OFFLINE_PREVIEW_PASSED',executedAt:new Date().toISOString(),htmlFilename:path.basename(file),htmlSHA256:hash(file),bytes:fs.statSync(file).size,browserVersion:browser.version(),checks,externalRequests:external,errors};
  fs.writeFileSync(path.join(web,'offline-validation.json'),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result));
}finally{await browser.close();}
